#!/usr/bin/env python3
"""Build the master documents from entry files.

Decisions live in ``docs/decisions/``, one file per decision. Tool-table
rows live in ``docs/tools/``. This script writes ``docs/DECISIONS.md`` and
the marked tool table in ``README.md``.

    python3 tools/build_docs.py
    python3 tools/build_docs.py --check

``--check`` validates entry format and the generated-section markers. It
does not compare a master document with the entries, so a pull request can
add an entry without editing the master. After the entries land on ``main``,
``.github/workflows/regenerate-docs.yml`` opens one pull request with the
rebuilt masters.

A symlink, a junction, or a file with another name is not read or written.
The generator stays on the file the repository path names.
"""

from __future__ import annotations

import argparse
import errno
import hashlib
import os
import re
import stat
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path

DECISIONS_DIR = "docs/decisions"
TOOLS_DIR = "docs/tools"
DECISIONS_MASTER = "docs/DECISIONS.md"
README_MASTER = "README.md"

TOOLS_START = "<!-- generated:tools -->"
TOOLS_END = "<!-- /generated:tools -->"

DECISION_FILENAME = re.compile(r"^(\d{4}-\d{2}-\d{2})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
TOOL_FILENAME = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*\.md$")
DATE_HEADING = re.compile(r"^## (\d{4}-\d{2}-\d{2})$")
DATE_TOKEN = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ORDER_TOKEN = re.compile(r"^[1-9][0-9]*$")
SEPARATOR_CELL = re.compile(r"^:?-{3,}:?$")
# Windows treats these stems as devices even when they have an extension.
RESERVED_STEM = re.compile(r"^(con|prn|aux|nul|com[1-9]|lpt[1-9])$", re.I)

DECISION_NOTE = (
    "This file is generated by `tools/build_docs.py` from the files in "
    "[docs/decisions/](decisions/). Add a decision by adding a file there. "
    "Do not edit this file by hand."
)
DECISION_ORDER_NOTE = (
    "The log lists each date newest first. On a date, a file with no `order` "
    "key is listed by file name, ahead of files that set `order`. Leave "
    "`order` unset on a new file. Entries stay in the folder. The file format "
    "is in [CONTRIBUTING.md](../CONTRIBUTING.md)."
)
TOOL_NOTE = (
    "This table is generated by `tools/build_docs.py` from the files in "
    "[docs/tools/](docs/tools/). Add a tool by adding a file there. "
    "Do not edit this table by hand."
)


class FormatProblem(ValueError):
    """One entry file failed validation."""


# A mount-point reparse tag is a Windows junction. Other reparse tags, such as
# a placeholder for a file that is not stored locally, are left alone.
_MOUNT_POINT = 0xA0000003


def _absolute(path: Path) -> Path:
    """Absolute path without resolving a symlink or junction."""
    return Path(os.path.abspath(path))


def _lstat(path: Path):
    try:
        return os.lstat(path)
    except OSError:
        return None


def _is_symlink(path: Path) -> bool:
    info = _lstat(path)
    return info is not None and stat.S_ISLNK(info.st_mode)


def _is_junction(path: Path) -> bool:
    """True for a Windows directory junction, including on Python 3.11."""
    checker = getattr(os.path, "isjunction", None)
    if checker is not None:
        try:
            return bool(checker(os.fspath(path)))
        except (OSError, ValueError):
            return False
    if os.name != "nt" or _lstat(path) is None:
        return False
    return _mount_point(path)


def _mount_point(path: Path) -> bool:
    import ctypes
    from ctypes import wintypes

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    get_attrs = kernel32.GetFileAttributesW
    get_attrs.argtypes = [wintypes.LPCWSTR]
    get_attrs.restype = wintypes.DWORD
    attributes = get_attrs(os.fspath(path))
    if attributes == 0xFFFFFFFF or not attributes & 0x400:
        return False
    create = kernel32.CreateFileW
    create.argtypes = [
        wintypes.LPCWSTR,
        wintypes.DWORD,
        wintypes.DWORD,
        ctypes.c_void_p,
        wintypes.DWORD,
        wintypes.DWORD,
        ctypes.c_void_p,
    ]
    create.restype = ctypes.c_void_p
    handle = create(
        os.fspath(path),
        0x80,
        0x1 | 0x2 | 0x4,
        None,
        3,
        0x02000000 | 0x00200000,
        None,
    )
    invalid = ctypes.c_void_p(-1).value
    if not handle or handle == invalid:
        return False
    try:
        buffer = ctypes.create_string_buffer(16 * 1024)
        returned = wintypes.DWORD(0)
        control = kernel32.DeviceIoControl
        control.argtypes = [
            ctypes.c_void_p,
            wintypes.DWORD,
            ctypes.c_void_p,
            wintypes.DWORD,
            ctypes.c_void_p,
            wintypes.DWORD,
            ctypes.POINTER(wintypes.DWORD),
            ctypes.c_void_p,
        ]
        control.restype = wintypes.BOOL
        ok = control(handle, 0x000900A8, None, 0, buffer, len(buffer), ctypes.byref(returned), None)
        if not ok or returned.value < 4:
            return False
        tag = int.from_bytes(buffer.raw[:4], "little")
        return tag == _MOUNT_POINT
    finally:
        close = kernel32.CloseHandle
        close.argtypes = [ctypes.c_void_p]
        close.restype = wintypes.BOOL
        close(handle)


def _extra_name(path: Path) -> bool:
    """True when a regular file has another directory entry."""
    info = _lstat(path)
    if info is None or stat.S_ISLNK(info.st_mode) or stat.S_ISDIR(info.st_mode):
        return False
    return info.st_nlink > 1


def _link_problem(root: Path, path: Path) -> str | None:
    """The repository-relative component that is a link, if any.

    Ancestors of ``root`` are not checked. A checkout directory can sit under
    a symlink, and that directory is still the repository.
    """
    root_abs = _absolute(root)
    path_abs = _absolute(path)
    try:
        relative = path_abs.relative_to(root_abs)
    except ValueError:
        return "path is outside the repository"
    current = root_abs
    walked: list[str] = []
    for part in relative.parts:
        walked.append(part)
        current = current / part
        if _is_symlink(current) or _is_junction(current) or _extra_name(current):
            return f"{'/'.join(walked)}: a link is not followed"
        if _lstat(current) is None:
            return None
    return None


def _refuse_link(path: Path, root: Path | None) -> None:
    if root is not None:
        problem = _link_problem(root, path)
        if problem:
            raise FormatProblem(problem)
        return
    if _is_symlink(path) or _is_junction(path) or _extra_name(path):
        raise FormatProblem(f"{path.name}: a link is not followed")


def _link_errno(exc: OSError) -> bool:
    return exc.errno in {errno.ELOOP, getattr(errno, "EMLINK", -1)}


def _read_bytes(path: Path) -> bytes:
    flags = os.O_RDONLY
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(path, flags)
    with os.fdopen(fd, "rb") as handle:
        return handle.read()


def _write_bytes(path: Path, data: bytes) -> None:
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(path, flags, 0o644)
    with os.fdopen(fd, "wb") as handle:
        handle.write(data)


@dataclass(frozen=True)
class DecisionEntry:
    filename: str
    date: date
    decision: str
    rationale: str
    order: int | None


@dataclass(frozen=True)
class ToolEntry:
    filename: str
    tool: str
    summary: str
    order: int | None


def normalize_repo_path(path: str) -> str:
    """Return a repository-relative path that uses ``/``.

    Absolute paths and ``..`` are rejected. Backslashes are separators, so a
    Windows relative path names the same entry as a POSIX one.
    """
    text = str(path).replace("\\", "/").strip()
    if re.match(r"^[A-Za-z]:", text) or text.startswith("/") or text.startswith("//"):
        raise ValueError(f"absolute path is not a repository path: {path}")
    parts: list[str] = []
    for part in text.split("/"):
        if part in ("", "."):
            continue
        if part == "..":
            raise ValueError(f"path leaves the repository: {path}")
        parts.append(part)
    if not parts:
        raise ValueError("empty repository path")
    return "/".join(parts)


def entry_directory(root: Path, relative: str) -> Path:
    """Join ``relative`` under ``root`` without treating ``\\`` as a name."""
    path = root
    for part in normalize_repo_path(relative).split("/"):
        path = path / part
    return path


def repo_relative(root: Path, file: Path) -> str:
    return "/".join(file.relative_to(root).parts)


def read_text(path: Path, *, root: Path | None = None) -> str:
    """Read UTF-8 text and return LF endings, including from a CRLF checkout.

    The final component is opened without following a symlink. When ``root``
    is set, a symlink or junction in any component under that directory is
    refused before the open.
    """
    _refuse_link(path, root)
    try:
        raw = _read_bytes(path)
    except OSError as exc:
        if _link_errno(exc):
            raise FormatProblem(f"{path.name}: a link is not followed") from exc
        raise
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise FormatProblem("file is not utf-8 text") from exc
    if text.startswith("\ufeff"):
        raise FormatProblem("byte order mark is not allowed")
    if "\x00" in text:
        raise FormatProblem("file is not utf-8 text")
    return text.replace("\r\n", "\n").replace("\r", "\n")


def write_text(path: Path, text: str, *, root: Path | None = None) -> None:
    """Write LF only, including on Windows where the default translation is CRLF.

    Nothing is written when the path, or a parent under ``root``, is a link.
    """
    _refuse_link(path, root)
    path.parent.mkdir(parents=True, exist_ok=True)
    _refuse_link(path, root)
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    try:
        _write_bytes(path, normalized.encode("utf-8"))
    except OSError as exc:
        if _link_errno(exc):
            raise FormatProblem(f"{path.name}: a link is not followed") from exc
        raise


def escape_cell(text: str) -> str:
    return text.replace("|", "\\|")


def split_cells(line: str) -> list[str]:
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    cells: list[str] = []
    current: list[str] = []
    index = 0
    while index < len(body):
        if body[index] == "\\" and index + 1 < len(body) and body[index + 1] == "|":
            current.append("|")
            index += 2
            continue
        if body[index] == "|":
            cells.append("".join(current).strip())
            current = []
            index += 1
            continue
        current.append(body[index])
        index += 1
    cells.append("".join(current).strip())
    return cells


def _is_separator(cells: list[str]) -> bool:
    return bool(cells) and all(SEPARATOR_CELL.fullmatch(cell) for cell in cells)


def parse_decision_tables(text: str) -> list[tuple[str, str, str]]:
    """Return ``(date, decision, rationale)`` rows in document order."""
    rows: list[tuple[str, str, str]] = []
    current: str | None = None
    for raw in text.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        heading = DATE_HEADING.fullmatch(raw.strip())
        if heading:
            current = heading.group(1)
            date.fromisoformat(current)
            continue
        if current is None or not raw.startswith("|"):
            continue
        cells = split_cells(raw)
        if _is_separator(cells) or cells == ["Decision", "Rationale"]:
            continue
        if len(cells) != 2 or not cells[0] or not cells[1]:
            raise FormatProblem(f"decision table row needs two cells: {raw}")
        rows.append((current, cells[0], cells[1]))
    return rows


def parse_tool_table(text: str) -> list[tuple[str, str]]:
    """Return ``(tool, summary)`` rows from the first tool table."""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    start: int | None = None
    for index, line in enumerate(lines):
        if split_cells(line) == ["Tool", "What it does"] if line.startswith("|") else False:
            start = index
            break
    if start is None:
        raise FormatProblem("tool table is missing")
    rows: list[tuple[str, str]] = []
    for line in lines[start + 1 :]:
        if not line.startswith("|"):
            break
        cells = split_cells(line)
        if _is_separator(cells):
            continue
        if len(cells) != 2 or not cells[0] or not cells[1]:
            raise FormatProblem(f"tool table row needs two cells: {line}")
        rows.append((cells[0], cells[1]))
    if not rows:
        raise FormatProblem("tool table has no rows")
    return rows


def slugify(text: str, limit: int = 72) -> str:
    pieces: list[str] = []
    for char in text.lower():
        if char.isascii() and char.isalnum():
            pieces.append(char)
        else:
            pieces.append("-")
    slug = "".join(pieces)
    while "--" in slug:
        slug = slug.replace("--", "-")
    slug = slug.strip("-")
    if len(slug) > limit:
        cut = slug[:limit]
        if "-" in cut:
            head, _, _ = cut.rpartition("-")
            if head:
                cut = head
        slug = cut.strip("-")
    return slug or "entry"


def unique_slug(text: str, used: set[str], limit: int = 72) -> str:
    """Pick a slug that is not already in ``used``.

    A second text that shortens to the same slug gets a content hash, not
    the next integer. Two branches never have to pick the same sequence number.
    """
    base = slugify(text, limit=limit)
    if RESERVED_STEM.fullmatch(base):
        base = f"{base}-entry"
    if base not in used:
        used.add(base)
        return base
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]
    candidate = f"{base}-{digest}"
    if candidate in used:
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
        candidate = f"{base}-{digest}"
    used.add(candidate)
    return candidate


def _split_front_matter(text: str) -> tuple[dict[str, str] | None, str]:
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 4)
    if end < 0:
        raise FormatProblem("front matter is not closed")
    raw = text[4:end]
    body = text[end + len("\n---\n") :]
    fields: dict[str, str] = {}
    if raw == "":
        return fields, body
    for line in raw.split("\n"):
        if line == "":
            raise FormatProblem("front matter has a blank line")
        if ":" not in line:
            raise FormatProblem(f"front matter line has no key: {line}")
        key, value = line.split(":", 1)
        if key != key.strip() or not key or not key.replace("-", "").isalnum():
            raise FormatProblem(f"front matter key is not valid: {key}")
        if key in fields:
            raise FormatProblem(f"front matter key is repeated: {key}")
        fields[key] = value.strip()
    return fields, body


# Characters that start another line in a master document without being "\n".
_LINE_BREAKS = ("\n", "\r", "\v", "\f", "\u0085", "\u2028", "\u2029")


def _require_one_line(label: str, text: str) -> None:
    if any(mark in text for mark in _LINE_BREAKS):
        raise FormatProblem(f"{label} must be one line")
    if "<!--" in text:
        raise FormatProblem(f"{label} cannot include a comment")


def _parse_title_body(body: str) -> tuple[str, str]:
    if not body.endswith("\n"):
        raise FormatProblem("file must end with a newline")
    if body.startswith("\n"):
        body = body[1:]
    lines = body.split("\n")
    if not lines or lines[-1] != "":
        raise FormatProblem("file must end with a newline")
    lines = lines[:-1]
    if len(lines) != 3 or lines[1] != "":
        raise FormatProblem("expected a title, a blank line, and one rationale line")
    title_line, _blank, rationale = lines
    if not title_line.startswith("# ") or title_line.startswith("## "):
        raise FormatProblem("title must be one '# ' heading")
    title = title_line[2:]
    if not title or title != title.strip():
        raise FormatProblem("title must be one non-empty line")
    if not rationale or rationale != rationale.strip():
        raise FormatProblem("rationale must be one non-empty line")
    _require_one_line("title", title)
    _require_one_line("rationale", rationale)
    return title, rationale


def _parse_order(fields: dict[str, str]) -> int | None:
    if "order" not in fields:
        return None
    token = fields["order"]
    if not ORDER_TOKEN.fullmatch(token):
        raise FormatProblem("order must be a positive integer without a leading zero")
    return int(token)


def parse_decision_file(filename: str, text: str) -> DecisionEntry:
    match = DECISION_FILENAME.fullmatch(filename)
    if match is None:
        raise FormatProblem(
            "file name must be YYYY-MM-DD-short-slug.md, using lowercase words, not a sequence number"
        )
    if RESERVED_STEM.fullmatch(Path(filename).stem):
        raise FormatProblem("file name is a Windows reserved device name")
    file_date = match.group(1)
    try:
        parsed_date = date.fromisoformat(file_date)
    except ValueError as exc:
        raise FormatProblem(f"file name date is not a real day: {file_date}") from exc
    fields, body = _split_front_matter(text)
    if fields is None:
        raise FormatProblem("decision file needs front matter with a date")
    unknown = sorted(set(fields) - {"date", "order"})
    if unknown:
        raise FormatProblem(f"unknown front matter key: {', '.join(unknown)}")
    if "date" not in fields:
        raise FormatProblem("front matter needs a date")
    if fields["date"] != file_date or not DATE_TOKEN.fullmatch(fields["date"]):
        raise FormatProblem("front matter date must match the file name")
    try:
        if date.fromisoformat(fields["date"]) != parsed_date:
            raise FormatProblem("front matter date must match the file name")
    except ValueError as exc:
        raise FormatProblem("front matter date is not a real day") from exc
    title, rationale = _parse_title_body(body)
    return DecisionEntry(
        filename=filename,
        date=parsed_date,
        decision=title,
        rationale=rationale,
        order=_parse_order(fields),
    )


def parse_tool_file(filename: str, text: str) -> ToolEntry:
    if TOOL_FILENAME.fullmatch(filename) is None:
        raise FormatProblem("file name must be a lowercase slug such as inspect-part.md")
    if RESERVED_STEM.fullmatch(Path(filename).stem):
        raise FormatProblem("file name is a Windows reserved device name")
    fields, body = _split_front_matter(text)
    if fields is None:
        order = None
    else:
        unknown = sorted(set(fields) - {"order"})
        if unknown:
            raise FormatProblem(f"unknown front matter key: {', '.join(unknown)}")
        order = _parse_order(fields)
    title, summary = _parse_title_body(body)
    return ToolEntry(filename=filename, tool=title, summary=summary, order=order)


def format_decision_file(entry: DecisionEntry) -> str:
    lines = ["---", f"date: {entry.date.isoformat()}"]
    if entry.order is not None:
        lines.append(f"order: {entry.order}")
    lines.extend(["---", "", f"# {entry.decision}", "", entry.rationale, ""])
    return "\n".join(lines)


def format_tool_file(entry: ToolEntry) -> str:
    lines: list[str] = []
    if entry.order is not None:
        lines.extend(["---", f"order: {entry.order}", "---", ""])
    lines.extend([f"# {entry.tool}", "", entry.summary, ""])
    return "\n".join(lines)


def _iter_markdown(root: Path, relative: str) -> tuple[list[Path], list[str]]:
    folder = entry_directory(root, relative)
    errors: list[str] = []
    problem = _link_problem(root, folder)
    if problem:
        return [], [problem]
    if not folder.is_dir():
        return [], [f"{normalize_repo_path(relative)}: entry folder is missing"]
    files: list[Path] = []
    try:
        children = list(folder.iterdir())
    except OSError:
        return [], [f"{normalize_repo_path(relative)}: entry folder is missing"]
    for child in children:
        problem = _link_problem(root, child)
        if problem:
            errors.append(problem)
            continue
        rel = repo_relative(root, child)
        if child.is_file() and child.suffix == ".md":
            files.append(child)
            continue
        errors.append(f"{rel}: entry folder only holds markdown entry files")
    files.sort(key=lambda item: item.name)
    return files, errors


def load_decisions(root: Path) -> tuple[list[DecisionEntry], list[str]]:
    files, errors = _iter_markdown(root, DECISIONS_DIR)
    entries: list[DecisionEntry] = []
    for file in files:
        rel = repo_relative(root, file)
        try:
            entries.append(parse_decision_file(file.name, read_text(file, root=root)))
        except FormatProblem as exc:
            errors.append(f"{rel}: {exc}")
    return entries, errors


def load_tools(root: Path) -> tuple[list[ToolEntry], list[str]]:
    files, errors = _iter_markdown(root, TOOLS_DIR)
    entries: list[ToolEntry] = []
    for file in files:
        rel = repo_relative(root, file)
        try:
            entries.append(parse_tool_file(file.name, read_text(file, root=root)))
        except FormatProblem as exc:
            errors.append(f"{rel}: {exc}")
    return entries, errors


def sort_decisions(entries: list[DecisionEntry]) -> list[DecisionEntry]:
    def key(entry: DecisionEntry) -> tuple:
        # Unset order sorts by file name ahead of the migrated sequence.
        # A shared order key stays stable because the file name breaks the tie.
        if entry.order is None:
            return (-entry.date.toordinal(), 0, entry.filename, 0, entry.filename)
        return (-entry.date.toordinal(), 1, "", entry.order, entry.filename)

    return sorted(entries, key=key)


def sort_tools(entries: list[ToolEntry]) -> list[ToolEntry]:
    def key(entry: ToolEntry) -> tuple:
        if entry.order is None:
            return (1, 0, entry.filename)
        return (0, entry.order, entry.filename)

    return sorted(entries, key=key)


def render_decisions(entries: list[DecisionEntry]) -> str:
    ordered = sort_decisions(entries)
    header = "\n".join(
        [
            "# Decisions",
            "",
            DECISION_NOTE,
            "",
            "Choices that later work should keep, unless a new entry overturns them.",
            "",
            DECISION_ORDER_NOTE,
        ]
    )
    sections: list[str] = [header]
    index = 0
    while index < len(ordered):
        current = ordered[index].date
        rows = [f"## {current.isoformat()}", "", "| Decision | Rationale |", "| --- | --- |"]
        while index < len(ordered) and ordered[index].date == current:
            entry = ordered[index]
            rows.append(f"| {escape_cell(entry.decision)} | {escape_cell(entry.rationale)} |")
            index += 1
        sections.append("\n".join(rows))
    sections.append("## Related\n\n- [Principles](PRINCIPLES.md)\n- [Roadmap](ROADMAP.md)\n")
    return "\n\n".join(sections)


def render_tools_inner(entries: list[ToolEntry]) -> str:
    lines = [TOOL_NOTE, "", "| Tool | What it does |", "| --- | --- |"]
    for entry in sort_tools(entries):
        lines.append(f"| {escape_cell(entry.tool)} | {escape_cell(entry.summary)} |")
    return "\n".join(lines)


def render_tools_block(entries: list[ToolEntry]) -> str:
    return f"{TOOLS_START}\n{render_tools_inner(entries)}\n{TOOLS_END}\n"


def replace_marked_tools(text: str, block: str) -> str | None:
    start = text.find(TOOLS_START)
    end = text.find(TOOLS_END)
    if start < 0 or end < 0 or end < start:
        return None
    line_end = text.find("\n", end)
    if line_end < 0:
        line_end = len(text)
    else:
        line_end += 1
    return text[:start] + block + text[line_end:]


def replace_raw_tool_table(text: str, block: str) -> str:
    """Replace the unmarked tool table. Used once, when markers are added."""
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = normalized.split("\n")
    start: int | None = None
    for index, line in enumerate(lines):
        if line.startswith("|") and split_cells(line) == ["Tool", "What it does"]:
            start = index
            break
    if start is None:
        raise FormatProblem("README.md: tool table is missing")
    end = start + 1
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    replacement = block.rstrip("\n").split("\n")
    rewritten = lines[:start] + replacement + lines[end:]
    result = "\n".join(rewritten)
    if normalized.endswith("\n") and not result.endswith("\n"):
        result += "\n"
    return result


def update_readme(text: str, entries: list[ToolEntry]) -> str:
    block = render_tools_block(entries)
    if TOOLS_START in text or TOOLS_END in text:
        marked = replace_marked_tools(text, block)
        if marked is None:
            raise FormatProblem("README.md: missing generated tools markers")
        return marked
    return replace_raw_tool_table(text, block)


def _decision_filename(day: date, decision: str, used: set[str]) -> str:
    slug = unique_slug(decision, used)
    return f"{day.isoformat()}-{slug}.md"


def align_decision_entries(
    entries: list[DecisionEntry], rows: list[tuple[str, str, str]]
) -> list[DecisionEntry]:
    """Match ``rows`` to existing files and number them in that order.

    A row with no file yet becomes a new entry. A file whose decision is not
    in ``rows`` is kept after the rows for its date. Nothing is deleted.
    """
    pools: dict[tuple[str, str], list[DecisionEntry]] = {}
    for entry in entries:
        pools.setdefault((entry.date.isoformat(), entry.decision), []).append(entry)
    used: set[int] = set()
    used_names: dict[str, set[str]] = {}
    for entry in entries:
        used_names.setdefault(entry.date.isoformat(), set()).add(entry.filename)
    counts: dict[str, int] = {}
    aligned: list[DecisionEntry] = []

    def take_order(day: str) -> int:
        counts[day] = counts.get(day, 0) + 1
        return counts[day]

    for day, decision, rationale in rows:
        parsed = date.fromisoformat(day)
        pool = pools.get((day, decision), [])
        chosen: DecisionEntry | None = None
        for candidate in pool:
            if id(candidate) not in used:
                chosen = candidate
                used.add(id(candidate))
                break
        order = take_order(day)
        if chosen is None:
            names = used_names.setdefault(day, set())
            slugs = {name[len(day) + 1 : -3] for name in names if name.startswith(f"{day}-")}
            filename = _decision_filename(parsed, decision, slugs)
            names.add(filename)
            aligned.append(DecisionEntry(filename, parsed, decision, rationale, order))
            continue
        aligned.append(
            DecisionEntry(chosen.filename, parsed, decision, rationale, order)
        )
    for entry in entries:
        if id(entry) in used:
            continue
        day = entry.date.isoformat()
        aligned.append(
            DecisionEntry(
                entry.filename,
                entry.date,
                entry.decision,
                entry.rationale,
                take_order(day),
            )
        )
    return aligned


def decision_entries_from_log(text: str) -> list[DecisionEntry]:
    return align_decision_entries([], parse_decision_tables(text))


def align_tool_entries(entries: list[ToolEntry], rows: list[tuple[str, str]]) -> list[ToolEntry]:
    pools: dict[str, list[ToolEntry]] = {}
    for entry in entries:
        pools.setdefault(entry.tool, []).append(entry)
    used: set[int] = set()
    used_slugs = {entry.filename[: -len(".md")] for entry in entries}
    aligned: list[ToolEntry] = []
    order = 0
    for tool, summary in rows:
        order += 1
        chosen: ToolEntry | None = None
        for candidate in pools.get(tool, []):
            if id(candidate) not in used:
                chosen = candidate
                used.add(id(candidate))
                break
        if chosen is None:
            slug = unique_slug(tool, used_slugs)
            aligned.append(ToolEntry(f"{slug}.md", tool, summary, order))
            continue
        aligned.append(ToolEntry(chosen.filename, tool, summary, order))
    for entry in entries:
        if id(entry) in used:
            continue
        order += 1
        aligned.append(ToolEntry(entry.filename, entry.tool, entry.summary, order))
    return aligned


def tool_entries_from_table(text: str) -> list[ToolEntry]:
    return align_tool_entries([], parse_tool_table(text))


